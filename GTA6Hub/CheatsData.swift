/// Ein Cheat aus der In-Game-Liste (Fortschritt → Cheats, nach der Story).
/// Name, Effekt und Freischalt-Bedingung stammen aus den öffentlichen
/// Guides (The Loadout, TrueAchievements, ComicBook, KeenGamer — Stand
/// 25.11.2026, gegenseitig abgeglichen). Von den 61 D-Pad-Codes sind
/// bisher 19 öffentlich dokumentiert; die übrigen zeigt das Spiel selbst
/// erst nach dem Freischalten — hier steht dann „noch nicht entdeckt",
/// statt irgendetwas zu erfinden.
struct CheatEntry: Identifiable {
    let id: String
    let category: CheatCategory
    let name: String
    let effectDE: String
    let effectEN: String
    let unlockDE: String
    let unlockEN: String
    /// D-Pad-Folge als Pfeile (↑ ↓ ← →) — nil = öffentlich noch nicht entdeckt.
    let code: String?
}

enum CheatCategory: String, CaseIterable, Identifiable {
    case player
    case combat
    case vehicles
    case environment
    case filters

    var id: String { rawValue }

    func title(_ store: AppStore) -> String {
        switch self {
        case .player: return store.tr("Spieler", "Player")
        case .combat: return store.tr("Kampf", "Combat")
        case .vehicles: return store.tr("Fahrzeuge spawnen", "Spawn Vehicles")
        case .environment: return store.tr("Umwelt & Wetter", "Environment")
        case .filters: return store.tr("Bildfilter", "Screen Filters")
        }
    }

    var icon: String {
        switch self {
        case .player: return "person.fill"
        case .combat: return "scope"
        case .vehicles: return "car.fill"
        case .environment: return "cloud.sun.fill"
        case .filters: return "camera.filters"
        }
    }
}

